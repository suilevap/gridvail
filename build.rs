use std::{env, fs, path::PathBuf};

fn main() {
    let maps = files("maps", "txt");
    write(
        "bundled_maps.rs",
        &table(
            "maps",
            "txt",
            "BUNDLED_MAPS",
            "(&str, &str)",
            &maps,
            |name| format!("{name:?}"),
        ),
    );
    let effects = files("effects", "ron");
    write("effect_ids.rs", &effect_ids(&effects));
    write(
        "bundled_effects.rs",
        &table(
            "effects",
            "ron",
            "BUNDLED_EFFECTS",
            "(EffectId, &str)",
            &effects,
            |name| format!("EffectId::{}", variant(name)),
        ),
    );
}

/// Every `assets/<directory>/*.<extension>`, by name (its file name without
/// the extension), sorted, with its path.
fn files(directory: &str, extension: &str) -> Vec<(String, PathBuf)> {
    let path = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap())
        .join("assets")
        .join(directory);
    // Watching the directory also catches newly added or removed files.
    println!("cargo:rerun-if-changed={}", path.display());
    let mut files: Vec<_> = fs::read_dir(&path)
        .unwrap_or_else(|_| panic!("read assets/{directory}"))
        .map(|entry| entry.expect("read directory entry").path())
        .filter(|path| path.is_file() && path.extension().is_some_and(|ext| ext == extension))
        .map(|path| {
            let name = path.file_stem().unwrap().to_str().expect("UTF-8 file name");
            (name.to_string(), path)
        })
        .collect();
    files.sort();
    files
}

/// A table `name` of `(key, text)` for each file, the key made by `key`.
fn table(
    directory: &str,
    extension: &str,
    name: &str,
    entry: &str,
    files: &[(String, PathBuf)],
    key: impl Fn(&str) -> String,
) -> String {
    let mut source = format!(
        "/// Every file in `assets/{directory}` (`*.{extension}`), with its text, \
         generated by `build.rs`.\npub const {name}: &[{entry}] = &[\n"
    );
    for (file, path) in files {
        source.push_str(&format!(
            "    ({}, include_str!({:?})),\n",
            key(file),
            path.to_str().expect("UTF-8 path")
        ));
    }
    source.push_str("];\n");
    source
}

/// The enum naming every effect: one variant per file in
/// `assets/effects`, its name in UpperCamelCase (`blood.ron` is `Blood`).
fn effect_ids(files: &[(String, PathBuf)]) -> String {
    let variants: Vec<String> = files.iter().map(|(name, _)| variant(name)).collect();
    let mut sorted = variants.clone();
    sorted.sort();
    sorted.dedup();
    assert_eq!(
        sorted.len(),
        variants.len(),
        "two effect files make one name"
    );
    let mut source = String::from(
        "/// An effect: one variant per file in `assets/effects`, generated by\n\
         /// `build.rs` (`blood.ron` is `Blood`), so a new effect is a new file.\n\
         /// Code names an effect by its variant and data by the same word\n\
         /// (`bleeds: Blood`), so a name nobody wrote fails to compile or to\n\
         /// read, and nothing in play carries or looks up a string.\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, serde::Deserialize)]\n\
         pub enum EffectId {\n",
    );
    for variant in &variants {
        source.push_str(&format!("    {variant},\n"));
    }
    source.push_str("}\n\nimpl EffectId {\n    /// Every effect, in file name order.\n");
    source.push_str(&format!(
        "    pub const ALL: [EffectId; {}] = [{}];\n}}\n",
        variants.len(),
        variants
            .iter()
            .map(|variant| format!("EffectId::{variant}"))
            .collect::<Vec<_>>()
            .join(", ")
    ));
    source
}

/// `slam_heavy` as `SlamHeavy`.
fn variant(name: &str) -> String {
    name.split(['_', '-', ' '])
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            let first = chars.next().unwrap().to_ascii_uppercase();
            first.to_string() + chars.as_str()
        })
        .collect()
}

fn write(file: &str, source: &str) {
    let output = PathBuf::from(env::var_os("OUT_DIR").unwrap()).join(file);
    fs::write(output, source).expect("write generated table");
}
