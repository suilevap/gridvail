use std::{env, fs, path::PathBuf};

/// Catalogs: kinds of things the game is made of, one file each in
/// `assets/<folder>` (`*.ron`), named in code and data by a generated enum
/// (`WeaponId::Sweep` for `assets/weapons/sweep.ron`). A new thing of a kind
/// is a new file; a new kind is a new folder and a line here.
const CATALOGS: &[(&str, &str)] = &[
    ("effects", "EffectId"),
    ("weapons", "WeaponId"),
    ("moves", "MovesId"),
    ("actors", "ActorId"),
];

fn main() {
    // Maps stay named: a map names the next by file, and the page and the
    // command line choose them by name.
    let maps = files("maps", "txt");
    let mut source = String::from(
        "/// Every map in `assets/maps`, by name (its file name without `.txt`),\n\
         /// generated by `build.rs`.\npub const BUNDLED_MAPS: &[(&str, &str)] = &[\n",
    );
    for (name, path) in &maps {
        source.push_str(&format!("    ({name:?}, include_str!({path:?})),\n"));
    }
    source.push_str("];\n");
    write("bundled_maps.rs", &source);

    let (mut ids, mut texts) = (String::new(), String::new());
    for (folder, id) in CATALOGS {
        let files = files(folder, "ron");
        ids.push_str(&catalog_id(folder, id, &files));
        texts.push_str(&catalog_texts(id, &files));
    }
    write("catalog_ids.rs", &ids);
    write("catalog_texts.rs", &texts);
}

/// Every `assets/<folder>/*.<extension>`, by name (its file name without the
/// extension), sorted, with its path.
fn files(folder: &str, extension: &str) -> Vec<(String, String)> {
    let path = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap())
        .join("assets")
        .join(folder);
    // Watching the folder also catches newly added or removed files.
    println!("cargo:rerun-if-changed={}", path.display());
    let mut files: Vec<_> = fs::read_dir(&path)
        .unwrap_or_else(|_| panic!("read assets/{folder}"))
        .map(|entry| entry.expect("read folder entry").path())
        .filter(|path| path.is_file() && path.extension().is_some_and(|ext| ext == extension))
        .map(|path| {
            let name = path.file_stem().unwrap().to_str().expect("UTF-8 file name");
            (
                name.to_string(),
                path.to_str().expect("UTF-8 path").to_string(),
            )
        })
        .collect();
    files.sort();
    files
}

/// The enum naming every file of a catalog (one variant each, its name in
/// UpperCamelCase: `blood.ron` is `Blood`) and its `CatalogId`.
fn catalog_id(folder: &str, id: &str, files: &[(String, String)]) -> String {
    let variants: Vec<String> = files.iter().map(|(name, _)| variant(name)).collect();
    let mut unique = variants.clone();
    unique.sort();
    unique.dedup();
    assert_eq!(
        unique.len(),
        variants.len(),
        "two files in assets/{folder} make one name"
    );
    let list = |each: &dyn Fn(usize) -> String| {
        (0..variants.len()).map(each).collect::<Vec<_>>().join(", ")
    };
    format!(
        "/// One of `assets/{folder}`: a variant per file, generated by `build.rs`\n\
         /// (`{example}.ron` is `{id}::{first}`). Code and data name one by its\n\
         /// variant, so a name nobody wrote fails to compile or to read.\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, serde::Deserialize)]\n\
         pub enum {id} {{ {variants} }}\n\n\
         impl CatalogId for {id} {{\n    \
             const ALL: &'static [Self] = &[{all}];\n    \
             const FILES: &'static [&'static str] = &[{names}];\n    \
             fn index(self) -> usize {{ self as usize }}\n\
         }}\n\n",
        example = files.first().map_or("", |(name, _)| name.as_str()),
        first = variants.first().map_or("", String::as_str),
        variants = list(&|i| variants[i].clone()),
        all = list(&|i| format!("Self::{}", variants[i])),
        names = list(&|i| format!("{:?}", files[i].0)),
    )
}

/// The bundled text of every file of a catalog, by its id.
fn catalog_texts(id: &str, files: &[(String, String)]) -> String {
    let texts = files
        .iter()
        .map(|(_, path)| format!("include_str!({path:?})"))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "impl Bundled for {id} {{\n    const TEXTS: &'static [&'static str] = &[{texts}];\n}}\n\n"
    )
}

/// `slam_heavy` as `SlamHeavy`.
fn variant(name: &str) -> String {
    name.split(['_', '-', ' '])
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            let first = chars.next().unwrap().to_ascii_uppercase();
            first.to_string() + chars.as_str()
        })
        .collect()
}

fn write(file: &str, source: &str) {
    let output = PathBuf::from(env::var_os("OUT_DIR").unwrap()).join(file);
    fs::write(output, source).expect("write generated table");
}
